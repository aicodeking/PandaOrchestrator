"""v1/v2/v3 (+ a10 ablation) comparison from eval_reports/v3/*.json -> eval_reports/compare_v3.md.

  .venv/bin/python scripts/eval/compare_v3.py
"""

import json
from pathlib import Path

R = Path("eval_reports/v3")
M = {"v1": "panda-router-v1", "v2": "panda-router-v2", "v3": "panda-router-v3", "a10": "v3_32_a10 (anchor 1.0)"}
# scripts/train/bench.py int8 batch-1, run back to back (checkpoints/logs/v3_queue.log); idle-host v2 from its metrics.json
LOADED = {"v1": ["13.0", "41.6"], "v2": ["36.9", "162.2"], "v3": ["40.1", "170.7"], "a10": ["28.9", "132.6"]}
UNLOADED = {"v2": ["9.6", "18.6"]}
SIZE = {"v1": "panda-router-v1", "v2": "panda-router-v2", "v3": "panda-router-v3", "a10": "v3_32_a10_onnx"}


def load(p):
    return json.loads((R / p).read_text()) if (R / p).exists() else None


def g(d, *k):
    for x in k:
        if not isinstance(d, dict) or x not in d:
            return None
        d = d[x]
    return d


def f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head), *("| " + " | ".join(r) + " |" for r in rows), ""]


def prof(split):
    rows = []
    for k, n in M.items():
        d = load(f"{k}_{split}.json")
        if d:
            m = d["profiler_metrics"]
            rows.append([n, str(d["n"]), f(m["category"]["acc"]), f(m["difficulty"]["mae"]), f(m["difficulty"]["spearman"]),
                         f(m["flags"]["auroc_macro"]), f(m["checklist"]["f1_macro"]), f(m["out_tokens"]["mae_log10"])])
    return table(["model", "n", "cat acc", "diff MAE", "diff ρ", "flags AUROC", "checklist F1", "out_tok MAE"], rows)


def routing():
    rows = []
    for k, n in M.items():
        d = load(f"{k}_gold.json")
        if d:
            mu, ch = (g(d, "routing", "metrics", "predicted", p) or {} for p in ("max_utility", "cheapest_above_threshold"))
            rows.append([n, f(mu.get("utility_regret"), 4), f(mu.get("pick_agreement")), f(ch.get("cost_ratio")),
                         f(ch.get("below_min_p_rate")), f(g(d, "routing", "metrics", "predicted", "all", "utility_regret"), 4)])
    return table(["model", "max_util regret", "max_util agree", "cheapest cost ratio", "cheapest below-min-P", "all-policy regret"], rows)


def outcome():
    rows = []
    for k, n in M.items():
        d = load(f"outcome_{k}.json")
        if d:
            h = d["heldout_issue"]
            rows.append([n, f"{f(h['spearman'])} ({f(h['ci95'][0])}..{f(h['ci95'][1])})", f(g(d, "heldout_issue_within_repo", "spearman")),
                         f(g(d, "heldout_issue_nsys100", "spearman"))])
    return table(["model", "SWE held-out ρ (95% CI)", "within-repo ρ", "n_systems≥100 ρ"], rows)


def attempts(suffix):
    rows = []
    for k, n in M.items():
        d = load(f"attempt_{k}{suffix}.json")
        if d:
            p = d["routing"]["policies"]
            c = lambda pol: f"{p[pol]['success_per_100']:.1f} / ${p[pol]['cost_per_100_usd']:.3f}"
            rows.append([n, f(d["attempt_irt"]["spearman"]), c("cheapest_above_threshold"), c("max_utility"),
                         c("always_cheapest"), c("always_strongest")])
    return table(["model", "attempt-IRT ρ", "cheapest_above_thr succ / $ per 100", "max_utility succ / $", "always_cheapest",
                  "always_strongest"], rows)


def hard():
    t = Path("eval_reports/v3/hard_tasks.md")
    if not t.exists():
        return []
    c = [x.strip() for x in t.read_text().strip().splitlines()[-1].strip("|").split("|")][3:]
    return table(["", *M.values()], [["pass rate", *(x.strip("*") for x in c)]])


def size_latency():
    rows = []
    for k, a in SIZE.items():
        d = json.loads(Path(f"artifacts/{a}/metrics.json").read_text())
        rows.append([M[k], f(g(d, "size_mb", "int8"), 1), *LOADED[k], *(UNLOADED.get(k, ["-", "-"]))])
    return table(["model", "int8 MB", "p50 ms (load ~30)", "p95 ms (load ~30)", "p50 ms (v2 stored, idle host)", "p95 ms"], rows)


md = ["# Panda Router v3 vs v2 vs v1", "", "Generated by `scripts/eval/compare_v3.py` from `eval_reports/v3/*.json`.", "",
      "## Gold (359 real tasks)", "", *prof("gold"), "## Test (603)", "", *prof("test"), "## Fresh test (310)", "", *prof("testfresh"),
      "## Routing on gold (predicted vs oracle profile, 50 random pools/task)", "", *routing(),
      "## SWE-bench outcome-difficulty Spearman (held-out repos/issues)", "", *outcome(),
      "## TRUE routed success on gold attempts (140 tasks, 5 attempter cards), current matcher", "", *attempts(""),
      "Same eval with `PANDA_ROUTER_CALIBRATION=off`:", "", *attempts("_nocal"),
      "## Hard-task pass rate (21 hand-written tasks)", "", *hard(),
      "## Size and CPU latency (batch 1, int8; same architecture for all four, so differences are host-load noise)", "", *size_latency()]
Path("eval_reports/compare_v3.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
