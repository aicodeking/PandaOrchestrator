"""v1 vs v2 comparison report from eval_reports/v2/*.json -> eval_reports/compare_v2.md.

  .venv/bin/python scripts/eval/compare_v2.py fixed_average heuristic knn panda-router-v1 v2_t150m ... \
      --ship panda-router-v2 --out eval_reports/compare_v2.md

Each name needs eval_reports/v2/<name>_{gold,test,testfresh}.json; outcome_<name>.json is optional
(outcome_v1.json is used for panda-router-v1).
"""

import argparse
import json
from pathlib import Path

R = Path("eval_reports/v2")
OUTCOME_ALIAS = {"panda-router-v1": "v1"}


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def get(d, *path):
    for k in path:
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def profiler_table(names: list[str], split: str) -> list[str]:
    rows = ["| model | n | category acc | difficulty MAE | difficulty ρ | flags AUROC | checklist F1 | out_tokens MAE |",
            "|---|---|---|---|---|---|---|---|"]
    for n in names:
        d = load(R / f"{n}_{split}.json")
        if d is None:
            continue
        m = d["profiler_metrics"]
        rows.append(f"| {n} | {d['n']} | {f(m['category']['acc'])} | {f(m['difficulty']['mae'])} | "
                    f"{f(m['difficulty']['spearman'])} | {f(m['flags']['auroc_macro'])} | {f(m['checklist']['f1_macro'])} | "
                    f"{f(m['out_tokens']['mae_log10'])} |")
    return rows


def routing_table(names: list[str]) -> list[str]:
    rows = ["| model | max_utility agree | max_utility regret | cheapest agree | cheapest cost ratio | cheapest P<0.75 |",
            "|---|---|---|---|---|---|"]
    for n in names:
        d = load(R / f"{n}_gold.json")
        if d is None:
            continue
        mu = get(d, "routing", "metrics", "predicted", "max_utility") or {}
        ch = get(d, "routing", "metrics", "predicted", "cheapest_above_threshold") or {}
        rows.append(f"| {n} | {f(mu.get('pick_agreement'))} | {f(mu.get('utility_regret'), 4)} | {f(ch.get('pick_agreement'))} | "
                    f"{f(ch.get('cost_ratio'))} | {f(ch.get('below_min_p_rate'))} |")
    return rows


def outcome_table(names: list[str]) -> list[str]:
    rows = ["| model | held-out ρ (95% CI) | held-out within-repo ρ | held-out n_systems≥100 ρ | all 2,594 ρ (report ctx) |",
            "|---|---|---|---|---|"]
    for n in names:
        d = load(R / f"outcome_{OUTCOME_ALIAS.get(n, n)}.json")
        if d is None:
            continue
        h = d["heldout_issue"]
        rows.append(f"| {n} | {f(h['spearman'])} ({f(h['ci95'][0])}..{f(h['ci95'][1])}) | "
                    f"{f(get(d, 'heldout_issue_within_repo', 'spearman'))} | {f(d['heldout_issue_nsys100']['spearman'])} | "
                    f"{f(d['all_report']['spearman'])} |")
    return rows


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("names", nargs="+")
    ap.add_argument("--out", default="eval_reports/compare_v2.md")
    a = ap.parse_args()
    md = ["# Panda Router v1 vs v2", "", "Generated by `scripts/eval/compare_v2.py` from `eval_reports/v2/*.json`.", "",
          "## Gold (329 real tasks, never trained on)", "", *profiler_table(a.names, "gold"), "",
          "## Test (364; 244 of these rows were in v1's training split, so v1 is inflated here)", "",
          *profiler_table(a.names, "test"), "",
          "## Fresh test (120 test rows not in v1's training split)", "", *profiler_table(a.names, "testfresh"), "",
          "## Routing (gold, 50 random card pools per task, oracle = teacher-label profile)", "", *routing_table(a.names), "",
          "## Outcome-difficulty Spearman (expected difficulty vs SWE-bench IRT b)", "",
          "Held-out = 980 tasks from repos never trained on (`checkpoints/outcome/heldout.jsonl`). `all` includes the "
          "anchor training tasks, so only v1/baselines are clean there.", "", *outcome_table(a.names), ""]
    hard = Path("eval_reports/v2/hard_tasks.md")
    if hard.exists():
        md += ["## Hand-written hard-task check", "", hard.read_text()]
    Path(a.out).write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
